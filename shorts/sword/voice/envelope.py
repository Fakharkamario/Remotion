# voice.wav -> src/videos/sword/voicedata.ts: per-frame mouth openness (0..1, 30 fps) + word onsets in frames
import json, subprocess, numpy as np
raw = subprocess.run(["ffmpeg","-v","error","-i","shorts/sword/voice/voice.wav","-ac","1","-ar","48000","-f","f32le","-"],capture_output=True).stdout
x = np.frombuffer(raw, np.float32); sr = 48000; hop = sr // 30
n = len(x) // hop + 1
rms = np.array([np.sqrt(np.mean(x[i*hop:(i+1)*hop+hop//2]**2) + 1e-12) for i in range(n)])
db = 20*np.log10(rms + 1e-9); lo, hi = np.percentile(db[db > -60], [20, 97]) if (db > -60).any() else (-40, -10)
m = np.clip((db - (lo - 3)) / (hi - lo + 3), 0, 1) ** 1.3
m[db < -42] = 0
W = json.load(open("shorts/sword/voice/words.json"))
out = "// generated by shorts/sword/voice/envelope.py — do not edit\n"
out += "export const MOUTH: number[] = [" + ",".join(f"{v:.2f}" for v in m) + "];\n"
out += "export const WORDS: [string, number, number][] = [\n" + ",\n".join(f"  [{json.dumps(w['w'])}, {w['s']*30:.1f}, {w['e']*30:.1f}]" for w in W) + "\n];\n"
open("src/videos/sword/voicedata.ts","w").write(out)
print(n, "frames")
